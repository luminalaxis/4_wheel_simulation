def fillet_polygon(vertices, closed: bool):
    """Turn a polygon with a corner radius per vertex into straight/arc segments.

    Each vertex ``(x, y, radius)`` is rounded with a tangent arc, so a closed polygon
    always gives a geometrically closed lap. Returns ``("S", length)`` and
    ``("C", radius, angle_deg)`` tuples (angle > 0 = left).
    """
    pts = [np.array(v[:2], dtype=float) for v in vertices]
    radii = [float(v[2]) for v in vertices]
    n = len(pts)
    corner_idx = range(n) if closed else range(1, n - 1)
    angle, tangent = {}, {}
    for i in corner_idx:
        a = pts[i] - pts[i - 1]
        b = pts[(i + 1) % n] - pts[i]
        th = math.atan2(a[0] * b[1] - a[1] * b[0], float(a @ b))
        angle[i] = th
        tangent[i] = radii[i] * math.tan(abs(th) / 2.0)
    segments = []
    for i in range(n if closed else n - 1):
        j = (i + 1) % n
        length = float(np.linalg.norm(pts[j] - pts[i])) - tangent.get(i, 0.0) - tangent.get(j, 0.0)
        if length < 1.0:
            raise ValueError(f"edge {i}->{j} too short for its corner radii")
        segments.append(("S", length))
        if j in angle:
            segments.append(("C", radii[j], math.degrees(angle[j])))
    return segments


def write_segments(path: Path, name: str, closed: bool, segments) -> float:
    total = 0.0
    with open(path, "w", newline="", encoding="utf-8") as fh:
        fh.write(f"# name: {name}\n# closed: {'true' if closed else 'false'}\n")
        w = csv.writer(fh)
        w.writerow(["type", "length_m", "radius_m", "direction"])
        for seg in segments:
            if seg[0] == "S":
                w.writerow(["straight", f"{seg[1]:.3f}", "", ""])
                total += seg[1]
            else:
                _, radius, ang = seg
                length = abs(math.radians(ang)) * radius
                w.writerow(["corner", f"{length:.3f}", f"{radius:g}", "left" if ang > 0 else "right"])
                total += length
    return total


# (x_m, y_m, corner_radius_m) - counter-clockwise closed loop
ENDURANCE = [(0, 0, 9), (55, 6, 25), (110, 0, 14), (160, 40, 18), (160, 80, 6), (125, 99, 10),
             (157, 131, 10), (125, 160, 10), (160, 192, 8), (88, 224, 22), (24, 205, 5),
             (72, 168, 10), (51, 125, 14), (3, 109, 9), (-29, 56, 16)]
# open course: first and last vertex are start and finish
AUTOCROSS = [(0, 0, 0), (60, 0, 9), (60, 45, 12), (20, 70, 10), (45, 95, 9), (20, 120, 9),
             (45, 145, 7), (100, 150, 6), (100, 100, 15), (150, 80, 11), (150, 20, 20),
             (100, -20, 8), (40, -30, 0)]


def main() -> None:
    (DATA / "aeromaps").mkdir(parents=True, exist_ok=True)
    (DATA / "tracks").mkdir(parents=True, exist_ok=True)
    write_grid_map(DATA / "aeromaps" / "fsae_example_grid.csv")
    write_cfd_points(DATA / "aeromaps" / "fsae_example_cfd_points.csv")

    total = write_segments(DATA / "tracks" / "fsae_endurance_example.csv",
                           "FSAE endurance example (closed loop)", True,
                           fillet_polygon(ENDURANCE, closed=True))
    print(f"endurance lap: {total:.1f} m")
    total = write_segments(DATA / "tracks" / "fsae_autocross_example.csv",
                           "FSAE autocross example (single lap, standing start)", False,
                           fillet_polygon(AUTOCROSS, closed=False))
    print(f"autocross lap: {total:.1f} m")

    write_segments(DATA / "tracks" / "fsae_accel.csv", "FSAE acceleration 75 m", False, [("S", 75.0)])
    write_segments(DATA / "tracks" / "fsae_skidpad.csv", "FSAE skidpad (9.125 m centre-line radius)",
                   True, [("C", 9.125, -360.0)])


if __name__ == "__main__":
    main()
