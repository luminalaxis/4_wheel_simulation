"""Generate the illustrative example data in ``data/`` (aero maps and FSAE-style tracks).

The aero map is a *synthetic* FSAE-like map with plausible trends (front wing and
undertray ground effect, rake sensitivity, roll and yaw losses, a DRS mode with the
rear-wing flap open). Replace it with your own CFD / wind-tunnel data for real work.

    python scripts/generate_example_data.py
"""

from __future__ import annotations

import csv
import math
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"

REAR_WING = {"high_df": (1.60, 0.68), "drs": (0.40, 0.24)}  # (ClA, CdA contribution)


def synthetic_aero(mode: str, rf, rr, roll, yaw):
    """ClA, CdA, cop_front for ride heights (mm), roll and yaw (deg)."""
    rf, rr, roll, yaw = (np.asarray(x, dtype=float) for x in (rf, rr, roll, yaw))
    d = 30.0 - rf
    fw = 1.15 * (1.0 + 0.012 * d - 0.0002 * d * d)  # front wing in ground effect
    hm = 0.5 * (rf + rr)
    rake = rr - rf
    dh = 35.0 - hm
    ut = 0.95 * (1.0 + 0.010 * dh - 0.0002 * dh * dh) * (1.0 + 0.006 * (rake - 10.0)
                                                         - 0.0002 * (rake - 10.0) ** 2)
    rw_cla, rw_cda = REAR_WING[mode]
    rw = rw_cla * np.ones_like(rf)
    fw = fw * (1.0 - 0.03 * roll ** 2) * (1.0 - 0.0025 * yaw ** 2)
    ut = ut * (1.0 - 0.04 * roll ** 2) * (1.0 - 0.004 * yaw ** 2)
    rw = rw * (1.0 - 0.002 * yaw ** 2)
    fw_cop, ut_cop, rw_cop = 1.32, 0.42 + 0.004 * (rake - 10.0), -0.20
    cla = fw + ut + rw
    cop = (fw * fw_cop + ut * ut_cop + rw * rw_cop) / cla
    cda = 0.36 + 0.16 * fw / 1.15 + 0.06 * ut / 0.95 + rw_cda * rw / rw_cla + 0.003 * yaw ** 2
    return cla, cda, cop


def write_grid_map(path: Path) -> None:
    rf_axis = np.arange(10.0, 50.1, 5.0)
    rr_axis = np.arange(15.0, 60.1, 5.0)
    roll_axis = np.arange(0.0, 2.01, 0.5)
    yaw_axis = np.arange(0.0, 8.01, 2.0)
    with open(path, "w", newline="", encoding="utf-8") as fh:
        fh.write("# Synthetic FSAE aero map (illustrative only) - generated by scripts/generate_example_data.py\n")
        fh.write("# ride heights at the axles in mm, roll and yaw in deg, ClA/CdA in m^2, cop_front = front share\n")
        w = csv.writer(fh)
        w.writerow(["mode", "front_rh_mm", "rear_rh_mm", "roll_deg", "yaw_deg", "ClA", "CdA", "cop_front"])
        for mode in REAR_WING:
            for rf in rf_axis:
                for rr in rr_axis:
                    for roll in roll_axis:
                        for yaw in yaw_axis:
                            cla, cda, cop = synthetic_aero(mode, rf, rr, roll, yaw)
                            w.writerow([mode, f"{rf:g}", f"{rr:g}", f"{roll:g}", f"{yaw:g}",
                                        f"{float(cla):.4f}", f"{float(cda):.4f}", f"{float(cop):.4f}"])


def write_cfd_points(path: Path, n: int = 36, seed: int = 7) -> None:
    rng = np.random.default_rng(seed)
    with open(path, "w", newline="", encoding="utf-8") as fh:
        fh.write("# Scattered 'CFD' samples of the synthetic map with 1 % noise (for aerolap fit-map)\n")
        w = csv.writer(fh)
        w.writerow(["mode", "front_rh_mm", "rear_rh_mm", "roll_deg", "ClA", "CdA", "cop_front"])
        for mode in REAR_WING:
            rf = rng.uniform(12.0, 48.0, n)
            rr = rng.uniform(18.0, 58.0, n)
            roll = rng.uniform(0.0, 2.0, n)
            cla, cda, cop = synthetic_aero(mode, rf, rr, roll, 0.0)
            cla = cla * (1.0 + 0.01 * rng.standard_normal(n))
            cda = cda * (1.0 + 0.01 * rng.standard_normal(n))
            for row in zip(rf, rr, roll, cla, cda, cop):
                w.writerow([mode] + [f"{x:.4f}" for x in row])


